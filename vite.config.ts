import { cloudflare } from "@cloudflare/vite-plugin";
import tailwindcss from "@tailwindcss/vite";
import { tanstackStart } from "@tanstack/react-start/plugin/vite";
import viteReact from "@vitejs/plugin-react";
import { defineConfig, loadEnv } from "vite";
import { tanstackSerwist } from "./plugins/tanstack-serwist.ts";

const env = loadEnv(process.env.NODE_ENV as string, process.cwd(), "VITE_");

export default defineConfig({
  base: env.VITE_PRERENDER ? "/Web-Osu-Mania/" : "/",
  server: {
    port: 3000,
  },
  plugins: [
    cloudflare({ viteEnvironment: { name: "ssr" } }),
    tanstackStart({
      prerender: {
        enabled: true,
        autoStaticPathsDiscovery: !!env.VITE_PRERENDER,
        crawlLinks: false,
      },
      pages: [
        {
          path: "/_shell",
          prerender: {
            enabled: true,
            outputPath: "/_shell.html",
          },
        },
      ],
    }),
    viteReact(),
    tailwindcss(),
    tanstackSerwist({
      globPatterns: ["**/*.*"], // Precache all static assets
      additionalPrecacheEntries: [
        // Manually add to precache because prerendered pages get generated by Tanstack Start after the server is built,
        // which is after the sw.js is generated.
        { url: "/_shell.html", revision: Date.now().toString() },
      ],
      maximumFileSizeToCacheInBytes: 5_000_000,
    }),
  ],
  resolve: {
    tsconfigPaths: true,
  },
});
